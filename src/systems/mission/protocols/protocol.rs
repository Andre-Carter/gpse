#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct ProtocolId(pub u8);

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ProtocolName(pub String);

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ProtocolCode(pub String);

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ProtocolKind {
    Accountability,
    NotOneLeftBehind,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Protocol {
    pub id: ProtocolId,
    pub name: ProtocolName,
    pub code: ProtocolCode,
    pub kind: ProtocolKind,
}

impl Protocol {
    pub fn new(
        id: ProtocolId,
        name: ProtocolName,
        code: ProtocolCode,
        kind: ProtocolKind,
    ) -> Self {
        Self {
            id,
            name,
            code,
            kind,
        }
    }
}

